#' Generate Party Identifiers
#'
#' Create 3-letter identifiers for parties when no party labels are supplied.
#'
#' @param x Integer: the number of parties.
#' @return A character vector of length \code{x} with deterministic 3-letter codes.
#'
#' @examples
#' if.parties.null(4)
#'
#' @export
if.parties.null <- function(x) {
  if (exists(".Random.seed", envir = .GlobalEnv)) {
    old_seed <- .Random.seed
    on.exit(assign(".Random.seed", old_seed, envir = .GlobalEnv))
  } else {
    on.exit(rm(".Random.seed", envir = .GlobalEnv))
  }
  set.seed(1)
  replicate(x, paste(sample(LETTERS, 3, replace = TRUE), collapse = ""))
}


#' Apply Electoral Threshold at Country Level
#'
#' Zeroes out votes for parties whose nationwide vote share falls strictly
#' below the country-level threshold, before district-level apportionment.
#' A party whose share equals the threshold is retained, matching the
#' threshold convention used by \code{divisorMethods} and \code{LR_Hamilton}.
#'
#' @param np Integer: number of parties.
#' @param ne Integer: number of elections.
#' @param nd Integer: number of districts.
#' @param threshold_country Numeric: vote-share threshold in \code{[0, 1]}.
#' @param sample A list generated by \code{sampleElectionData}.
#'
#' @return The modified sample with sub-threshold party votes set to 0.
#' @keywords internal
.countryThreshold <- function(np, ne, nd, threshold_country, sample) {
  for (j in seq_len(ne)) {
    if (nd > 1L) {
      row_sums <- apply(sample[[1]][, , j], 1, sum)
    } else {
      row_sums <- sample[[1]][, , j]
    }
    total <- sum(sample[[1]][, , j])
    vote_shares <- row_sums / total

    for (i in seq_len(np)) {
      if (vote_shares[i] < threshold_country) {
        sample[[1]][i, , j] <- 0
      }
    }
  }

  sample
}


#' Compute Ideal Seat Shares
#'
#' Computes the proportional ("ideal") seat shares at country level for each
#' party in each election.
#'
#' @param ne Integer: number of elections.
#' @param nd Integer: number of districts.
#' @param np Integer: number of parties.
#' @param sample A list generated by \code{sampleElectionData}.
#'
#' @return A \code{data.frame} with columns: \code{elec}, \code{SeatTotalIdeal},
#'   \code{SeatShareIdeal}, \code{Party}.
#' @keywords internal
.seatsIdeal <- function(ne, nd, np, sample) {
  result_list <- vector("list", ne)

  for (i in seq_len(ne)) {
    total_seats <- sum(sample[[2]][[i]])
    ideal_shares <- sample[[3]][[i]]
    ideal_totals <- ideal_shares * total_seats

    result_list[[i]] <- data.frame(
      elec = paste0("e", i),
      SeatTotalIdeal = ideal_totals,
      SeatShareIdeal = ideal_shares,
      Party = as.character(if.parties.null(np)),
      stringsAsFactors = FALSE
    )
    result_list[[i]] <- result_list[[i]][order(-result_list[[i]]$SeatShareIdeal), ]
  }

  do.call(rbind, result_list)
}


#' Country-level Election Outcomes under Proportional Representation
#'
#' Allocates seats at the district level using a specified apportionment method,
#' then aggregates to country-level results.
#'
#' @param sample A list generated by \code{sampleElectionData}.
#' @param formula Character: apportionment method code (e.g., \code{"dh"},
#'   \code{"sl"}, \code{"hamilton"}).
#' @param threshold Numeric: district-level threshold in \code{[0, 1]}.
#' @param threshold_country Numeric: country-level threshold in \code{[0, 1]}.
#'
#' @return A \code{data.frame} with district-level apportionment results
#'   including columns: \code{Party}, \code{Seats}, \code{SeatShare},
#'   \code{Votes}, \code{VoteShare}, \code{id}, \code{elec}, \code{dist},
#'   \code{distTS}.
#' @keywords internal
.ProportionalRepresentation <- function(sample,
                                        formula,
                                        threshold = 0,
                                        threshold_country = 0) {
  ne <- sample$Params[1]
  nd <- sample$Params[2]
  np <- sample$Params[3]

  no_seats_dist <- unlist(sample$Seats_Dist)
  if (any(no_seats_dist == 0))
    stop("There are districts with 0 seats.")

  if (threshold_country > 0 && threshold == 0) {
    sample <- .countryThreshold(np, ne, nd, threshold_country, sample)
    dist_threshold <- 0
  } else {
    dist_threshold <- threshold
  }

  party_labels <- if.parties.null(np)
  results <- vector("list", ne * nd)
  idx <- 1L

  for (j in seq_len(ne)) {
    for (i in seq_len(nd)) {
      district_votes <- sample[[1]][, i, j]
      district_seats <- sample[[2]][[j]][i]

      if (formula == "hamilton") {
        apport <- LR_Hamilton(
          parties = party_labels,
          votes = district_votes,
          seats = district_seats,
          threshold = dist_threshold,
          order_name = TRUE
        )
      } else {
        apport <- divisorMethods(
          parties = party_labels,
          votes = district_votes,
          seats = district_seats,
          method = formula,
          threshold = dist_threshold,
          order_name = TRUE
        )
      }

      apport$id <- paste0("e", j, "d", i)
      apport$elec <- paste0("e", j)
      apport$dist <- paste0("d", i)
      apport$distTS <- sample[[2]][[j]][i]

      results[[idx]] <- apport[, c("Party", "Seats", "SeatShare", "Votes",
                                   "VoteShare", "id", "elec", "dist", "distTS")]
      idx <- idx + 1L
    }
  }

  do.call(rbind, results)
}
